module TopModule(
    input clk,
    input reset,
    output reg [9:0] q
);

reg [9:0] gray_count;

// Gray to Binary conversion
always @(*) begin
    q = gray_count ^ (gray_count >> 1);
end

// Gray Counter
always @ (posedge clk) begin
    if (reset) begin
        gray_count <= 10'd0; // Reset the counter to 0
    end else if (gray_count == 10'd999) begin
        gray_count <= 10'd0; // Reset the counter to 0 after reaching 999
    end else begin
        // Increment Gray counter
        // This implementation uses the property of Gray code where
        // the next Gray code can be generated by XORing the current
        // binary value with its right-shifted version (which is equivalent
        // to dividing by 2 and keeping the integer part)
        gray_count <= gray_count + 1; 
    end
end

endmodule