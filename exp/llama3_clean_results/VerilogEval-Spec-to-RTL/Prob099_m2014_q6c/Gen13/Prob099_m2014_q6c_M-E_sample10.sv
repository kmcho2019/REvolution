module TopModule(
    input [5:0] y,
    input w,
    output reg Y1,
    output reg Y2,
    output reg Y3,
    output reg Y4
);

always @(*) begin
    case({y, w})
        // A (0) --0--> B
        6'b000001_0: {Y1, Y2, Y3, Y4} = 4'b0_1_0_0; // B
        // A (0) --1--> A
        6'b000001_1: {Y1, Y2, Y3, Y4} = 4'b1_0_0_0; // A
        // B (0) --0--> C
        6'b000010_0: {Y1, Y2, Y3, Y4} = 4'b0_0_1_0; // C
        // B (0) --1--> D
        6'b000010_1: {Y1, Y2, Y3, Y4} = 4'b0_0_0_1; // D
        // C (0) --0--> E
        6'b000100_0: {Y1, Y2, Y3, Y4} = 4'b0_0_0_0; // E
        // C (0) --1--> D
        6'b000100_1: {Y1, Y2, Y3, Y4} = 4'b0_0_0_1; // D
        // D (0) --0--> F
        6'b001000_0: {Y1, Y2, Y3, Y4} = 4'b0_0_0_0; // F
        // D (0) --1--> A
        6'b001000_1: {Y1, Y2, Y3, Y4} = 4'b1_0_0_0; // A
        // E (1) --0--> E
        6'b010000_0: {Y1, Y2, Y3, Y4} = 4'b0_0_0_0; // E
        // E (1) --1--> D
        6'b010000_1: {Y1, Y2, Y3, Y4} = 4'b0_0_0_1; // D
        // F (1) --0--> C
        6'b100000_0: {Y1, Y2, Y3, Y4} = 4'b0_0_1_0; // C
        // F (1) --1--> D
        6'b100000_1: {Y1, Y2, Y3, Y4} = 4'b0_0_0_1; // D
        default: {Y1, Y2, Y3, Y4} = 4'b0_0_0_0; // Default state
    endcase
end

endmodule