module TopModule(
    input [3:0] x,
    output f
);

assign f = (x[3:2] == 4'd0 && (x[1:0] == 2'd0 || x[1:0] == 2'd2)) ||
           (x[3:2] == 4'd3 && (x[1:0] == 2'd0 || x[1:0] == 2'd1 || x[1:0] == 2'd3)) ||
           (x[3:2] == 4'd2 && (x[1:0] == 2'd0 || x[1:0] == 2'd1 || x[1:0] == 2'd2));

endmodule