module TopModule(
    input  [5:0] y,
    input  w,
    output reg Y1,
    output reg Y3
);

    always @(*) begin
        case ({y, w})
            6'b000001_1: {Y1, Y3} = 2'b10_0; // A (0) --1--> B
            6'b000001_0: {Y1, Y3} = 2'b00_0; // A (0) --0--> A
            6'b000010_1: {Y1, Y3} = 2'b00_0; // B (0) --1--> C
            6'b000010_0: {Y1, Y3} = 2'b000_1; // B (0) --0--> D
            6'b000100_1: {Y1, Y3} = 2'b00_0; // C (0) --1--> E
            6'b000100_0: {Y1, Y3} = 2'b000_1; // C (0) --0--> D
            6'b001000_1: {Y1, Y3} = 2'b00_0; // D (0) --1--> F
            6'b001000_0: {Y1, Y3} = 2'b00_0; // D (0) --0--> A
            6'b010000_1: {Y1, Y3} = 2'b00_0; // E (1) --1--> E
            6'b010000_0: {Y1, Y3} = 2'b000_1; // E (1) --0--> D
            6'b100000_1: {Y1, Y3} = 2'b00_1; // F (1) --1--> C
            6'b100000_0: {Y1, Y3} = 2'b000_1; // F (1) --0--> D
            default: {Y1, Y3} = 2'b00_0; // Default case
        endcase
    end

endmodule