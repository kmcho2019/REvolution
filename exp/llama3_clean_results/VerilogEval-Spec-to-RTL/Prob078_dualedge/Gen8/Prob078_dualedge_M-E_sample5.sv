module TopModule(
    input clk,
    input d,
    output reg q
);

reg clk_enable;  // Clock enable signal generated by clock edge detector
reg prev_clk;    // Previous clock value for edge detection

// Clock edge detector
always @(posedge clk or negedge clk) begin
    prev_clk <= clk;
end

// Generate clock enable signal on every edge
always @(posedge clk or negedge clk) begin
    if (clk != prev_clk) begin
        clk_enable <= 1'b1;
    end else begin
        clk_enable <= 1'b0;
    end
end

// Single flip-flop with clock enable
always @(posedge clk) begin
    if (clk_enable) begin
        q <= d;
    end
end

endmodule