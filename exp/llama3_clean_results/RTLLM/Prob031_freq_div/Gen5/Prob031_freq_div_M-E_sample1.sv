module freq_div (
    input  wire  CLK_in, // Input clock signal
    input  wire  RST,    // Reset signal
    output reg   CLK_50, // Output clock signal with a frequency of CLK_in divided by 2
    output reg   CLK_10, // Output clock signal with a frequency of CLK_in divided by 10
    output reg   CLK_1   // Output clock signal with a frequency of CLK_in divided by 100
);

reg [9:0] shift_reg; // Shift register to generate output clocks

always @(posedge CLK_in or posedge RST) begin
    if (RST) begin
        // Reset the shift register
        shift_reg <= 10'b1000000000;
    end else begin
        // Shift the register to the right
        shift_reg <= {shift_reg[8:0], 1'b0};
    end
end

// Decode the shift register to generate output clocks
always @(*) begin
    // CLK_50 is generated by looking at the least significant bit of the shift register
    CLK_50 <= shift_reg[0];

    // CLK_10 is generated by looking at the third least significant bit of the shift register
    CLK_10 <= shift_reg[3];

    // CLK_1 is generated by looking at the ninth least significant bit of the shift register
    CLK_1 <= shift_reg[9];
end

endmodule