always @(*)
begin
    case ({A, B})
        // A > B cases
        8'b1000_0000, 8'b1000_0001, 8'b1000_0010, 8'b1000_0011,
        8'b1000_0100, 8'b1000_0101, 8'b1000_0110, 8'b1000_0111,
