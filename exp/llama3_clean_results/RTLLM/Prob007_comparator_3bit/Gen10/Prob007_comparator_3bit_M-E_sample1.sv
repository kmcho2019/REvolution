        8'b1010_1100, 8'b1010_1101, 8'b1010_1110, 8'b1010_1111,
        8'b1011_0000, 8'b1011_0001, 8'b1011_0010, 8'b1011_0011,
        8'b1011_0100, 8'b1011_0101, 8'b1011_0110, 8'b1011_0111,
        8'b1011_1000, 8'b1011_1001, 8'b1011_1010, 8'b1011_1011,
