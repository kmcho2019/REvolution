                A_greater = 1'b0;
                A_equal = 1'b0;
                A_less = 1'b1;
            end

        // A == B cases
        8'b0000_0000, 8'b0001_0001, 8'b0010_0010, 8'b0011_0011,
        8'b0100_0100, 8'b0101_0101, 8'b0110_0110, 8'b0111_0111,
        8'b1000_1000, 8'b1001_1001, 8'b1010_1010, 8'b1011_1011,
        8'b1100_1100, 8'b1101_1101, 8'b1110_1110, 8'b1111_1111:
            begin
                A_greater = 1'b0;
                A_equal = 1'b1;
                A_less = 1'b0;
            end

        default: 
            begin
                A_greater = 1'bx;
                A_equal = 1'bx;
                A_less = 1'bx;
            end
    endcase
end

endmodule