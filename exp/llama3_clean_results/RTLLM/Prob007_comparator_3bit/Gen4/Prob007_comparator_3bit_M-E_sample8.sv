module comparator_3bit(
    input [2:0] A,
    input [2:0] B,
    output reg A_greater,
    output reg A_equal,
    output reg A_less
);

always @(*) begin
    case({A, B})
        // A > B cases
        8'b0000_0001, 8'b0000_0010, 8'b0000_0100, 8'b0000_1000,
        8'b0001_0000, 8'b0001_0001, 8'b0001_0010, 8'b0001_0100, 8'b0001_1000,
        8'b0010_0000, 8'b0010_0001, 8'b0010_0010, 8'b0010_0100, 8'b0010_1000,
        8'b0011_0000, 8'b0011_0001, 8'b0011_0010, 8'b0011_0100, 8'b0011_1000,
        8'b0100_0000, 8'b0100_0001, 8'b0100_0010, 8'b0100_0100, 8'b0100_1000,
        8'b0101_0000, 8'b0101_0001, 8'b0101_0010, 8'b0101_0100, 8'b0101_1000,
        8'b0110_0000, 8'b0110_0001, 8'b0110_0010, 8'b0110_0100, 8'b0110_1000,
        8'b0111_0000, 8'b0111_0001, 8'b0111_0010, 8'b0111_0100, 8'b0111_1000,
        8'b1000_0000, 8'b1000_0001, 8'b1000_0010, 8'b1000_0100, 8'b1000_1000,
        8'b1001_0000, 8'b1001_0001, 8'b1001_0010, 8'b1001_0100, 8'b1001_1000,
        8'b1010_0000, 8'b1010_0001, 8'b1010_0010, 8'b1010_0100, 8'b1010_1000,
        8'b1011_0000, 8'b1011_0001, 8'b1011_0010, 8'b1011_0100, 8'b1011_1000,
        8'b1100_0000, 8'b1100_0001, 8'b1100_0010, 8'b1100_0100, 8'b1100_1000,
        8'b1101_0000, 8'b1101_0001, 8'b1101_0010, 8'b1101_0100, 8'b1101_1000,
        8'b1110_0000, 8'b1110_0001, 8'b1110_0010, 8'b1110_0100, 8'b1110_1000,
        8'b1111_0000, 8'b1111_0001, 8'b1111_0010, 8'b1111_0100, 8'b1111_1000: begin
            A_greater = 1'b1;
            A_equal = 1'b0;
            A_less = 1'b0;
        end
        // A == B cases
        8'b0000_0000, 8'b0001_0001, 8'b0010_0010, 8'b0011_0011,
        8'b0100_0100, 8'b0101_0101, 8'b0110_0110, 8'b0111_0111,
        8'b1000_1000, 8'b1001_1001, 8'b1010_1010, 8'b1011_1011,
        8'b1100_1100, 8'b1101_1101, 8'b1110_1110, 8'b1111_1111: begin
            A_greater = 1'b0;
            A_equal = 1'b1;
            A_less = 1'b0;
        end
        // A < B cases
        default: begin
            A_greater = 1'b0;
            A_equal = 1'b0;
            A_less = 1'b1;
        end
    endcase
end

endmodule