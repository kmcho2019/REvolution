// Define the barrel_shifter module
module barrel_shifter(
    input [7:0] in,  // Input to be shifted
    input [2:0] ctrl,  // Control signal
    output [7:0] out  // Shifted output
);

    // Perform shifts based on control bits
    wire [7:0] shift_by_1 = (ctrl[0] == 1'b1)? (in >> 1) : in;
    wire [7:0] shift_by_2 = (ctrl[1] == 1'b1)? (shift_by_1 >> 1) : shift_by_1;
    wire [7:0] shift_by_4 = (ctrl[2] == 1'b1)? (shift_by_2 >> 2) : shift_by_2;

    // Assign the final shifted output
    assign out = shift_by_4;

endmodule

