module TopModule(
    input [3:0] x,
    output f
);
    // Assign row = x[3:2], col = x[1:0]
    // Karnaugh map cells with 1:
    // row col value
    // 00 00 = 1 -> x[3]=0,x[2]=0,x[1]=0,x[0]=0
    // 00 10 = 1 -> x[3]=0,x[2]=0,x[1]=1,x[0]=0
    // 11 00 = 1 -> x[3]=1,x[2]=1,x[1]=0,x[0]=0
    // 11 01 = 1 -> x[3]=1,x[2]=1,x[1]=0,x[0]=1
    // 11 11 = 1 -> x[3]=1,x[2]=1,x[1]=1,x[0]=1
    // 10 00 = 1 -> x[3]=1,x[2]=0,x[1]=0,x[0]=0
    // 10 01 = 1 -> x[3]=1,x[2]=0,x[1]=0,x[0]=1
    // 10 10 = 1 -> x[3]=1,x[2]=0,x[1]=1,x[0]=0
    // 10 11 = 0
    // 01 all 0

    // Write minterms for each 1 cell:
    // 1) 0000: ~x3 & ~x2 & ~x1 & ~x0
    // 2) 0010: ~x3 & ~x2 & x1 & ~x0
    // 3) 1100: x3 & x2 & ~x1 & ~x0
    // 4) 1101: x3 & x2 & ~x1 & x0
    // 5) 1111: x3 & x2 & x1 & x0
    // 6) 1000: x3 & ~x2 & ~x1 & ~x0
    // 7) 1001: x3 & ~x2 & ~x1 & x0
    // 8) 1010: x3 & ~x2 & x1 & ~x0

    assign f = (~x[3] & ~x[2] & ~x[1] & ~x[0]) |
               (~x[3] & ~x[2] &  x[1] & ~x[0]) |
               ( x[3] &  x[2] & ~x[1] & ~x[0]) |
               ( x[3] &  x[2] & ~x[1] &  x[0]) |
               ( x[3] &  x[2] &  x[1] &  x[0]) |
               ( x[3] & ~x[2] & ~x[1] & ~x[0]) |
               ( x[3] & ~x[2] & ~x[1] &  x[0]) |
               ( x[3] & ~x[2] &  x[1] & ~x[0]);

endmodule