module TopModule(
    input [3:0] x,
    output f
);
    // All cases where f=1 from the K-map:
    // 1. x[3:2]=00 and x[1:0]=00 or 10
    // 2. x[3:2]=11 and x[1:0]=00 or 01 or 11
    // 3. x[3:2]=10 and x[1:0]=00 or 01 or 10
    
    assign f = (~x[3] & ~x[2] & ~x[1] & ~x[0]) |  // 00-00
               (~x[3] & ~x[2] & x[1] & ~x[0]) |   // 00-10
               (x[3] & x[2] & ~x[1] & ~x[0]) |    // 11-00
               (x[3] & x[2] & ~x[1] & x[0]) |     // 11-01
               (x[3] & x[2] & x[1] & x[0]) |      // 11-11
               (x[3] & ~x[2] & ~x[1] & ~x[0]) |  // 10-00
               (x[3] & ~x[2] & ~x[1] & x[0]) |    // 10-01
               (x[3] & ~x[2] & x[1] & ~x[0]);     // 10-10
endmodule