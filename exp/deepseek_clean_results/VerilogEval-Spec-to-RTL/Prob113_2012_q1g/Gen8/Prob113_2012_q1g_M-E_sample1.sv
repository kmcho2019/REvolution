module TopModule(
    input [3:0] x,
    output f
);
    // 16:1 multiplexer implementation
    assign f = (x == 4'b0000) ? 1'b1 :  // 0000
               (x == 4'b0001) ? 1'b0 :  // 0001
               (x == 4'b0010) ? 1'b1 :  // 0010
               (x == 4'b0011) ? 1'b0 :  // 0011
               (x == 4'b0100) ? 1'b0 :  // 0100
               (x == 4'b0101) ? 1'b0 :  // 0101
               (x == 4'b0110) ? 1'b0 :  // 0110
               (x == 4'b0111) ? 1'b0 :  // 0111
               (x == 4'b1000) ? 1'b1 :  // 1000
               (x == 4'b1001) ? 1'b1 :  // 1001
               (x == 4'b1010) ? 1'b1 :  // 1010
               (x == 4'b1011) ? 1'b0 :  // 1011
               (x == 4'b1100) ? 1'b1 :  // 1100
               (x == 4'b1101) ? 1'b1 :  // 1101
               (x == 4'b1110) ? 1'b0 :  // 1110
               (x == 4'b1111) ? 1'b1 :  // 1111
               1'b0;  // default case (should never occur)
endmodule