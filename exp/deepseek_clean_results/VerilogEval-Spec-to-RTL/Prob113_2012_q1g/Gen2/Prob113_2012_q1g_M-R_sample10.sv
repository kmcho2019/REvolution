module TopModule(
    input [3:0] x,
    output f
);
    assign f = (x == 4'b0000) |  // 00,00
               (x == 4'b0010) |  // 00,10
               (x == 4'b1100) |  // 11,00
               (x == 4'b1101) |  // 11,01
               (x == 4'b1111) |  // 11,11
               (x == 4'b1000) |  // 10,00
               (x == 4'b1001) |  // 10,01
               (x == 4'b1010);   // 10,10
endmodule