module edge_detect (
    input  wire clk,
    input  wire rst_n,
    input  wire a,
    output reg  rise,
    output reg  down
);

    reg a_d; // delayed version of 'a'

    // Register delayed 'a' with asynchronous reset
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n)
            a_d <= 1'b0;
        else
            a_d <= a;
    end

    // Detect edges and register outputs with async reset
    always @(posedge clk or negedge rst_n) begin
        if (!rst_n) begin
            rise <= 1'b0;
            down <= 1'b0;
        end else begin
            rise <= (~a_d) & a;  // rising edge detected
            down <= a_d & (~a);  // falling edge detected
        end
    end

endmodule