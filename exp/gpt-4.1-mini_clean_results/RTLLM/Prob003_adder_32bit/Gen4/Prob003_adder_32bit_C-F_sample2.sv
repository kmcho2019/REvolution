// 16-bit CLA block with hierarchical carry-lookahead using 4-bit groups
module cla_16bit(
    input  [15:0] A,
    input  [15:0] B,
    input         Cin,
    output [15:0] S,
    output        Cout
);
    // Bitwise propagate and generate
    wire [15:0] p = A ^ B;
    wire [15:0] g = A & B;

    // Group propagate and generate signals for 4 groups of 4 bits each
    wire [3:0] P_group;
    wire [3:0] G_group;

    genvar i;

    // Compute group propagate and generate signals (4-bit groups)
    generate
        for (i=0; i<4; i=i+1) begin : group_pg
            // For group i (bits 4*i+3 downto 4*i)
            // Group propagate = p3 & p2 & p1 & p0
            assign P_group[i] = &p[4*i +:4];
            // Group generate = g3 | (p3 & g2) | (p3 & p2 & g1) | (p3 & p2 & p1 & g0)
            assign G_group[i] =
                g[4*i+3] |
                (p[4*i+3] & g[4*i+2]) |
                (p[4*i+3] & p[4*i+2] & g[4*i+1]) |
                (p[4*i+3] & p[4*i+2] & p[4*i+1] & g[4*i]);
        end
    endgenerate

    // Carry signals for group boundaries Cg[0] to Cg[4]
    // Cg[0] = Cin, then each subsequent carry is generated by CLA formula for groups
    wire [4:0] Cg;
    assign Cg[0] = Cin;
    assign Cg[1] = G_group[0] | (P_group[0] & Cg[0]);
    assign Cg[2] = G_group[1] | (P_group[1] & Cg[1]);
    assign Cg[3] = G_group[2] | (P_group[2] & Cg[2]);
    assign Cg[4] = G_group[3] | (P_group[3] & Cg[3]);
    assign Cout = Cg[4];

    // Within each group, calculate internal carries c_internal[0..3]
    // c_internal[0] = carry-in to group (Cg[group_index])
    // c_internal[i] = g[i-1] | (p[i-1] & c_internal[i-1]) for i=1..3 within the group

    wire [15:0] c; // carries per bit, c[0] is carry-in to bit 0, up to c[15]
    // Assign carry-in to bit 0 = Cin
    assign c[0] = Cin;

    generate
        for (i=0; i<4; i=i+1) begin : group_carry_internal
            // Starting carry for group = Cg[i]
            wire c0 = Cg[i];
            assign c[4*i] = c0; // carry-in to bit 4*i

            // Internal carry bits within group:
            assign c[4*i + 1] = g[4*i]     | (p[4*i]     & c[4*i]);
            assign c[4*i + 2] = g[4*i + 1] | (p[4*i + 1] & c[4*i + 1]);
            assign c[4*i + 3] = g[4*i + 2] | (p[4*i + 2] & c[4*i + 2]);
            // Note: c[4*i + 4] = carry-in to next group handled by Cg[i+1], so no assignment here
        end
    endgenerate

    // Compute sum bits
    generate
        for (i=0; i<16; i=i+1) begin : sum_bits
            assign S[i] = p[i] ^ c[i];
        end
    endgenerate
endmodule

module adder_32bit(
    input  [32:1] A,
    input  [32:1] B,
    output [32:1] S,
    output        C32
);
    // Remap inputs from 1-based to 0-based for internal CLA blocks
    wire [15:0] A_low  = A[16:1];
    wire [15:0] B_low  = B[16:1];
    wire [15:0] A_high = A[32:17];
    wire [15:0] B_high = B[32:17];

    wire [15:0] S_low;
    wire [15:0] S_high;
    wire c16;

    // Lower 16-bit CLA
    cla_16bit cla_lower (
        .A   (A_low),
        .B   (B_low),
        .Cin (1'b0),
        .S   (S_low),
        .Cout(c16)
    );

    // Upper 16-bit CLA
    cla_16bit cla_upper (
        .A   (A_high),
        .B   (B_high),
        .Cin (c16),
        .S   (S_high),
        .Cout(C32)
    );

    // Assign sum outputs back to 1-based indexing
    assign S[16:1]  = S_low;
    assign S[32:17] = S_high;
endmodule