// Improved cla_16bit with hierarchical carry calculation using group PG/GG signals

module cla_16bit(
    input  [15:0] A,
    input  [15:0] B,
    input         Cin,
    output [15:0] S,
    output        Cout
);
    // Propagate and Generate signals per bit
    wire [15:0] P = A ^ B;
    wire [15:0] G = A & B;

    // Group propagate and generate signals for 4-bit blocks
    wire [3:0] PG;
    wire [3:0] GG;

    genvar i;
    generate
        for (i = 0; i < 4; i = i + 1) begin : group_pg_gg
            // Calculate group PG and GG for each 4-bit group:
            assign PG[i] = &P[4*i +: 4];
            assign GG[i] = G[4*i + 3]
                         | (P[4*i + 3] & G[4*i + 2])
                         | (P[4*i + 3] & P[4*i + 2] & G[4*i + 1])
                         | (P[4*i + 3] & P[4*i + 2] & P[4*i + 1] & G[4*i + 0]);
        end
    endgenerate

    // Compute carries for each group using hierarchical CLA logic
    wire [4:0] C; // carry for groups and overall block
    assign C[0] = Cin;
    assign C[1] = GG[0] | (PG[0] & C[0]);
    assign C[2] = GG[1] | (PG[1] & C[1]);
    assign C[3] = GG[2] | (PG[2] & C[2]);
    assign C[4] = GG[3] | (PG[3] & C[3]);
    assign Cout = C[4];

    // Compute carries for each bit inside each 4-bit group
    wire [15:0] carry_bits;
    generate
        for (i = 0; i < 4; i = i + 1) begin : bits_in_group
            wire c0 = C[i];
            wire c1, c2, c3;

            assign c1 = G[4*i + 0] | (P[4*i + 0] & c0);
            assign c2 = G[4*i + 1] | (P[4*i + 1] & c1);
            assign c3 = G[4*i + 2] | (P[4*i + 2] & c2);

            assign carry_bits[4*i + 0] = c0;
            assign carry_bits[4*i + 1] = c1;
            assign carry_bits[4*i + 2] = c2;
            assign carry_bits[4*i + 3] = c3;
        end
    endgenerate

    // Sum bits: sum_i = P_i ^ carry_i
    assign S = P ^ carry_bits;

endmodule

module adder_32bit(
    input  [32:1] A,
    input  [32:1] B,
    output [32:1] S,
    output        C32
);
    // Convert 1-based inputs to zero-based internally
    wire [15:0] A_low  = A[16:1];
    wire [15:0] B_low  = B[16:1];
    wire [15:0] A_high = A[32:17];
    wire [15:0] B_high = B[32:17];

    wire c16;
    wire [15:0] S_low;
    wire [15:0] S_high;

    // Instantiate lower 16-bit CLA block
    cla_16bit cla_lower (
        .A(A_low),
        .B(B_low),
        .Cin(1'b0),
        .S(S_low),
        .Cout(c16)
    );

    // Instantiate upper 16-bit CLA block with carry-in from lower block
    cla_16bit cla_upper (
        .A(A_high),
        .B(B_high),
        .Cin(c16),
        .S(S_high),
        .Cout(C32)
    );

    // Assign sum outputs with 1-based indexing
    assign S[16:1]  = S_low;
    assign S[32:17] = S_high;

endmodule