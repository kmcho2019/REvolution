module cla_4bit(
    input  [3:0] A,
    input  [3:0] B,
    input        Cin,
    output [3:0] S,
    output       PG,  // Group Propagate
    output       GG,  // Group Generate
    output       Cout // Carry out
);
    wire [3:0] P = A ^ B; // propagate per bit
    wire [3:0] G = A & B; // generate per bit

    // Internal carry signals within group
    wire c1, c2, c3;

    // Carry lookahead inside 4-bit group
    assign c1 = G[0] | (P[0] & Cin);
    assign c2 = G[1] | (P[1] & c1);
    assign c3 = G[2] | (P[2] & c2);
    assign Cout = G[3] | (P[3] & c3);

    // Group propagate: all bits propagate
    assign PG = &P;

    // Group generate: generated within group or propagated from carry in
    assign GG = G[3] | (P[3] & G[2]) | (P[3] & P[2] & G[1]) | (P[3] & P[2] & P[1] & G[0]);

    // Sum bits
    assign S[0] = P[0] ^ Cin;
    assign S[1] = P[1] ^ c1;
    assign S[2] = P[2] ^ c2;
    assign S[3] = P[3] ^ c3;

endmodule

