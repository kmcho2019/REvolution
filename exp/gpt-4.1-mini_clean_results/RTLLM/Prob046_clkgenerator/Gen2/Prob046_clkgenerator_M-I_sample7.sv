module clkgenerator #(
    parameter PERIOD = 10
)(
    input  wire clk_in,  // Input base clock
    output reg  clk      // Output clock generated by division
);

    // Counter width: enough bits to count up to PERIOD/2
    localparam COUNTER_WIDTH = $clog2(PERIOD/2);

    reg [COUNTER_WIDTH-1:0] count = 0;

    always @(posedge clk_in) begin
        if (count == (PERIOD/2 - 1)) begin
            clk <= ~clk;
            count <= 0;
        end else begin
            count <= count + 1;
        end
    end

    // Initialize clk to zero at the start (synthesizable if using FPGA tools with reset)
    initial clk = 0;

endmodule