module AndGate (
    output y,
    input  x1,
    input  x2
);
    and (y, x1, x2);
endmodule

module OrGate (
    output y,
    input  x1,
    input  x2
);
    or (y, x1, x2);
endmodule

module TopModule (
    input  a,
    input  b,
    input  c,
    input  d,
    output out,
    output out_n
);
    // Intermediate wires connecting AND gate outputs to OR gate inputs
    wire and_ab;
    wire and_cd;

    // First layer: two AND gates
    AndGate and_gate_ab (.y(and_ab), .x1(a), .x2(b));
    AndGate and_gate_cd (.y(and_cd), .x1(c), .x2(d));

    // Second layer: OR gate producing 'out'
    OrGate or_gate (.y(out), .x1(and_ab), .x2(and_cd));

    // Inverted output 'out_n' generated by NOT gate primitive on 'out'
    not not_gate (out_n, out);

endmodule