// TopModule: direct continuous assignments implement fundamental gates,
// complemented outputs formed by inverting fundamental gate outputs.
// This approach avoids separate modules while retaining clear, simple logic.

module TopModule(
    input  wire a,
    input  wire b,
    output wire out_and,
    output wire out_or,
    output wire out_xor,
    output wire out_nand,
    output wire out_nor,
    output wire out_xnor,
    output wire out_anotb
);

    // Fundamental gates implemented via continuous assignments
    assign out_and  = a & b;
    assign out_or   = a | b;
    assign out_xor  = a ^ b;
    assign out_anotb = a & ~b;

    // Complemented outputs generated by direct inversion of fundamentals
    assign out_nand = ~out_and;
    assign out_nor  = ~out_or;
    assign out_xnor = ~out_xor;

endmodule