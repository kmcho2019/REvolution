// Fundamental 2-input gate modules
module AND_gate(input wire x, input wire y, output wire z);
    assign z = x & y;
endmodule

module OR_gate(input wire x, input wire y, output wire z);
    assign z = x | y;
endmodule

module XOR_gate(input wire x, input wire y, output wire z);
    assign z = x ^ y;
endmodule

// AND_NOT gate module for a & ~b
module AND_NOT_gate(input wire x, input wire y, output wire z);
    assign z = x & ~y;
endmodule

// TopModule combines modular gate instantiations with direct inversion assigns
module TopModule (
    input  wire a,
    input  wire b,
    output wire out_and,
    output wire out_or,
    output wire out_xor,
    output wire out_nand,
    output wire out_nor,
    output wire out_xnor,
    output wire out_anotb
);

    // Intermediate wires for fundamental gates
    wire and_ab, or_ab, xor_ab;

    // Instantiate fundamental gates to preserve modularity and clarity
    AND_gate and_inst (.x(a), .y(b), .z(and_ab));
    OR_gate  or_inst  (.x(a), .y(b), .z(or_ab));
    XOR_gate xor_inst (.x(a), .y(b), .z(xor_ab));

    // Outputs from fundamental gates directly assigned
    assign out_and = and_ab;
    assign out_or  = or_ab;
    assign out_xor = xor_ab;

    // Complemented outputs generated by inverting intermediate wires (no extra inverter modules)
    assign out_nand = ~and_ab;
    assign out_nor  = ~or_ab;
    assign out_xnor = ~xor_ab;

    // out_anotb uses dedicated module for clear modular logic
    AND_NOT_gate and_not_inst (.x(a), .y(b), .z(out_anotb));

endmodule