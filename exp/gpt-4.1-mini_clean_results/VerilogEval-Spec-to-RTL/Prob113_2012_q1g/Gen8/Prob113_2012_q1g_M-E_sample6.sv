module TopModule(
    input  [3:0] x,
    output reg   f
);

always @(*) begin
    case (x)
        4'b0000: f = 1'b1; // x3x2=00, x1x0=00 => 1
        4'b0001: f = 1'b0; // 00 01 => 0
        4'b0011: f = 1'b0; // 00 11 => 0
        4'b0010: f = 1'b1; // 00 10 => 1
        4'b0100: f = 1'b0; // 01 00 => 0
        4'b0101: f = 1'b0; // 01 01 => 0
        4'b0111: f = 1'b0; // 01 11 => 0
        4'b0110: f = 1'b0; // 01 10 => 0
        4'b1100: f = 1'b1; // 11 00 => 1
        4'b1101: f = 1'b1; // 11 01 => 1
        4'b1111: f = 1'b1; // 11 11 => 1
        4'b1110: f = 1'b0; // 11 10 => 0
        4'b1000: f = 1'b1; // 10 00 => 1
        4'b1001: f = 1'b1; // 10 01 => 1
        4'b1011: f = 1'b0; // 10 11 => 0
        4'b1010: f = 1'b1; // 10 10 => 1
        default: f = 1'b0; // default safe case
    endcase
end

endmodule