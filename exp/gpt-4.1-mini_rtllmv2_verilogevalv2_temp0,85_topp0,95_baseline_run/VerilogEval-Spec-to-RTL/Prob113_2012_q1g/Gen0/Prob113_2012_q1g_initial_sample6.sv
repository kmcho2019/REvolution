module TopModule(
    input [3:0] x,
    output f
);
    // x[3], x[2]: row; x[1], x[0]: column
    // Karnaugh map (rows x[3:2], columns x[1:0]):
    // x[3:2] \ x[1:0] | 00 | 01 | 11 | 10
    // -----------------------------------
    //       00         | 1  | 0  | 0  | 1
    //       01         | 0  | 0  | 0  | 0
    //       11         | 1  | 1  | 1  | 0
    //       10         | 1  | 1  | 0  | 1

    // Minterms where f=1:
    // x=0000 (0)
    // x=0010 (2)
    // x=1100 (12)
    // x=1101 (13)
    // x=1111 (15)
    // x=1000 (8)
    // x=1001 (9)
    // x=1011 (11)
    // x=1010 (10)

    assign f = (x == 4'b0000) ||
               (x == 4'b0010) ||
               (x == 4'b1100) ||
               (x == 4'b1101) ||
               (x == 4'b1111) ||
               (x == 4'b1000) ||
               (x == 4'b1001) ||
               (x == 4'b1011) ||
               (x == 4'b1010);

endmodule