module TopModule (
  input in,
  input [9:0] state,
  output [9:0] next_state,
  output out1,
  output out2
);

assign next_state = (state == 10'b0000000001 & !in) ? 10'b0000000001 :  // S0, 0 -> S0
                    (state == 10'b0000000001 & in)  ? 10'b0000000010 :  // S0, 1 -> S1
                    (state == 10'b0000000010 & !in) ? 10'b0000000001 :  // S1, 0 -> S0
                    (state == 10'b0000000010 & in)  ? 10'b0000000100 :  // S1, 1 -> S2
                    (state == 10'b0000000100 & !in) ? 10'b0000000001 :  // S2, 0 -> S0
                    (state == 10'b0000000100 & in)  ? 10'b0000001000 :  // S2, 1 -> S3
                    (state == 10'b0000001000 & !in) ? 10'b0000000001 :  // S3, 0 -> S0
                    (state == 10'b0000001000 & in)  ? 10'b0000010000 :  // S3, 1 -> S4
                    (state == 10'b0000010000 & !in) ? 10'b0000000001 :  // S4, 0 -> S0
                    (state == 10'b0000010000 & in)  ? 10'b0000100000 :  // S4, 1 -> S5
                    (state == 10'b0000100000 & !in) ? 10'b0001000000 :  // S5, 0 -> S8
                    (state == 10'b0000100000 & in)  ? 10'b0010000000 :  // S5, 1 -> S6
                    (state == 10'b0001000000 & !in) ? 10'b0000000001 :  // S6, 0 -> S0
                    (state == 10'b0001000000 & in)  ? 10'b0000000001 :  // S6, 1 -> S7
                    (state == 10'b0010000000 & !in) ? 10'b0000000001 :  // S7, 0 -> S0
                    (state == 10'b0010000000 & in)  ? 10'b0010000000 :  // S7, 1 -> S7
                    (state == 10'b0100000000 & !in) ? 10'b0000000001 :  // S8, 0 -> S0
                    (state == 10'b0100000000 & in)  ? 10'b0000000010 :  // S8, 1 -> S1
                    (state == 10'b1000000000 & !in) ? 10'b0000000001 :  // S9, 0 -> S0
                    (state == 10'b1000000000 & in)  ? 10'b0000000010 :  // S9, 1 -> S1
                    10'b0000000000;  // Default case

assign out1 = (state == 10'b0010000000 | state == 10'b1000000000);
assign out2 = (state == 10'b0000000000 | state == 10'b0000000001);

endmodule