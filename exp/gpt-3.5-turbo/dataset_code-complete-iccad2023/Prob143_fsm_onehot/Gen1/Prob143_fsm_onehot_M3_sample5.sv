module TopModule (
  input in,
  input [9:0] state,
  output [9:0] next_state,
  output out1,
  output out2
);

assign next_state = (state == 10'b0000000001 && !in) ? 10'b0000000001 :
                    (state == 10'b0000000001 && in)  ? 10'b0000000010 :
                    (state == 10'b0000000010 && !in) ? 10'b0000000001 :
                    (state == 10'b0000000010 && in)  ? 10'b0000000100 :
                    (state == 10'b0000000100 && !in) ? 10'b0000000001 :
                    (state == 10'b0000000100 && in)  ? 10'b0000001000 :
                    (state == 10'b0000001000 && !in) ? 10'b0000000001 :
                    (state == 10'b0000001000 && in)  ? 10'b0000010000 :
                    (state == 10'b0000010000 && !in) ? 10'b0000000001 :
                    (state == 10'b0000010000 && in)  ? 10'b0000100000 :
                    (state == 10'b0000100000 && !in) ? 10'b0001000000 :
                    (state == 10'b0000100000 && in)  ? 10'b0010000000 :
                    (state == 10'b0001000000 && !in) ? 10'b0100000000 :
                    (state == 10'b0001000000 && in)  ? 10'b1000000000 :
                    (state == 10'b0010000000 && !in) ? 10'b0000000001 :
                    (state == 10'b0010000000 && in)  ? 10'b0010000000 :
                    (state == 10'b0100000000 && !in) ? 10'b0000000001 :
                    (state == 10'b0100000000 && in)  ? 10'b0000000010 :
                    (state == 10'b1000000000 && !in) ? 10'b0000000001 :
                    (state == 10'b1000000000 && in)  ? 10'b0000000010 :
                    10'b0000000000;

assign out1 = (state == 10'b0010000000 || state == 10'b1000000000) ? 1 : 0;
assign out2 = (state == 10'b0000000000 || state == 10'b0000000001) ? 1 : 0;

endmodule