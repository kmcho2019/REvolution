module TopModule (
  input [4:1] x,
  output logic f
);

assign f = 
  // x[1]x[2]x[3]x[4]
  // 00  01  11  10
  // 00 | 1 | 0 | 0 | 1 |
  // 01 | 0 | 0 | 0 | 0 |
  // 11 | 1 | 1 | 1 | 0 |
  // 10 | 1 | 1 | 0 | 1 |
  
  // Filling in the Karnaugh map values
  // Row 1
  (x[1] == 2'b00 && x[2] == 2'b00) || 
  (x[1] == 2'b10 && x[2] == 2'b00) || 
  // Row 2
  (x[1] == 2'b00 && x[2] == 2'b01) || 
  // Row 3
  (x[1] == 2'b00 && x[2] == 2'b11) || 
  (x[1] == 2'b01 && x[2] == 2'b11) || 
  (x[1] == 2'b10 && x[2] == 2'b11) || 
  // Row 4
  (x[1] == 2'b00 && x[2] == 2'b10) || 
  (x[1] == 2'b01 && x[2] == 2'b10) || 
  (x[1] == 2'b10 && x[2] == 2'b10);

endmodule