    input CLK_in,
    input RST,
    output reg CLK_50,
    output reg CLK_10,
    output reg CLK_1
);

reg [1:0] cnt_10;
reg [5:0] cnt_100;

always @(posedge CLK_in or posedge RST) begin
    if (RST) begin
        CLK_50 <= 1'b0;
        CLK_10 <= 1'b0;
        cnt_10 <= 2'b00;
        CLK_1 <= 1'b0;
        cnt_100 <= 6'b000000;
    end else begin
        // Generate 50MHz clock
        CLK_50 <= ~CLK_50;

        // Generate 10MHz clock
        if (cnt_10 == 4'b0100) begin
            CLK_10 <= ~CLK_10;
            cnt_10 <= 2'b00;
        end else begin
            cnt_10 <= cnt_10 + 1;
        end

        // Generate 1MHz clock
        if (cnt_100 == 6'b110001) begin
            CLK_1 <= ~CLK_1;
            cnt_100 <= 6'b000000;
        end else begin
            cnt_100 <= cnt_100 + 1;
        end
    end
end

endmodule
