module TopModule(
    input [3:0] x,
    output f
);

    assign f = (x[2] & x[3] & ~x[1] & ~x[0]) | // 00 11
               (x[2] & x[3] & x[1] & ~x[0]) | // 01 11
               (x[2] & x[3] & x[1] & x[0])  | // 11 11
               (~x[2] & ~x[3] & ~x[1] & ~x[0]) | // 00 00
               (~x[2] & x[3] & ~x[1] & ~x[0]) | // 00 10
               (~x[2] & x[3] & x[1] & ~x[0]) | // 01 10
               (x[2] & ~x[3] & ~x[1] & ~x[0]) | // 00 10
               (x[2] & ~x[3] & x[1] & x[0]);  // 11 10

endmodule