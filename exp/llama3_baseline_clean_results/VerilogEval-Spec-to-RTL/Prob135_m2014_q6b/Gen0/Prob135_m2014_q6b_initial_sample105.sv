module TopModule(
  input [2:0] y,
  input w,
  output Y1
);

assign Y1 = y[1];

always @(*)
  begin
    casez({y, w})
      // A (000) --0--> B (001)
      3'b0000: y[1] <= 0;
      // A (000) --1--> A (000)
      3'b0001: y[1] <= 0;
      // B (001) --0--> C (010)
      3'b0010: y[1] <= 1;
      // B (001) --1--> D (011)
      3'b0011: y[1] <= 1;
      // C (010) --0--> E (100)
      3'b0100: y[1] <= 0;
      // C (010) --1--> D (011)
      3'b0101: y[1] <= 1;
      // D (011) --0--> F (101)
      3'b0110: y[1] <= 1;
      // D (011) --1--> A (000)
      3'b0111: y[1] <= 0;
      // E (100) --0--> E (100)
      3'b1000: y[1] <= 0;
      // E (100) --1--> D (011)
      3'b1001: y[1] <= 1;
      // F (101) --0--> C (010)
      3'b1010: y[1] <= 1;
      // F (101) --1--> D (011)
      3'b1011: y[1] <= 1;
      default: y[1] <= 0;
    endcase
  end

endmodule