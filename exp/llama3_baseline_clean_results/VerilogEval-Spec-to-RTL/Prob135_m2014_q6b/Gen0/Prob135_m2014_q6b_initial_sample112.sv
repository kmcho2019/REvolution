module TopModule(
    input [2:0] y,
    input w,
    output Y1
);

    // Next-state logic for y[1]
    assign Y1 = ((y == 3'b001 && w == 1) ||  // B (001) and w = 1 -> A (000), y[1] = 0
                 (y == 3'b001 && w == 0) ||  // B (001) and w = 0 -> C (010), y[1] = 1
                 (y == 3'b010 && w == 1) ||  // C (010) and w = 1 -> D (011), y[1] = 1
                 (y == 3'b010 && w == 0) ||  // C (010) and w = 0 -> E (100), y[1] = 1
                 (y == 3'b011 && w == 1) ||  // D (011) and w = 1 -> A (000), y[1] = 0
                 (y == 3'b011 && w == 0) ||  // D (011) and w = 0 -> F (101), y[1] = 1
                 (y == 3'b100 && w == 1) ||  // E (100) and w = 1 -> D (011), y[1] = 1
                 (y == 3'b100 && w == 0) ||  // E (100) and w = 0 -> E (100), y[1] = 1
                 (y == 3'b101 && w == 1) ||  // F (101) and w = 1 -> D (011), y[1] = 1
                 (y == 3'b101 && w == 0)     // F (101) and w = 0 -> C (010), y[1] = 1
                );

endmodule